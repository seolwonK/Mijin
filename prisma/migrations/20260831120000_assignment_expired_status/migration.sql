--
-- 배정 후 업체·기사가 수락도 거절도 하지 않으면 지금까지는 관리자가 수동 회수하기
-- 전까지 영원히 REQUESTED 로 남았다(실사례: 8/21 배정 건이 열흘간 응답 대기 방치).
