/** 받침 유무에 따라 '을'/'를' 을 붙인다(한글 마지막 글자 기준, 그 외는 '을(를)'). */
export function withEul(word: string): string {
  const code = word.charCodeAt(word.length - 1);
  if (code < 0xac00 || code > 0xd7a3) return `${word}을(를)`;
  return `${word}${(code - 0xac00) % 28 === 0 ? '를' : '을'}`;
}
